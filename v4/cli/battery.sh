# so two ledgers that differ only in duplicated or whitespace-padded lines
# cannot pass as identical.
try:
    if file_sha256(ledger_path) != file_sha256(ledger_copy):
        problems.append("the ledger copies %s and %s are not byte-identical"
                        % (ledger_path, ledger_copy))
