            at_start = hang.get("host_at_attempt_start") or {}
            at_detect = hang.get("host_at_detection") or {}
            bits.append("run_queue %s->%s of nproc %s%s, deadline %ss, wedge %s" % (
                at_start.get("run_queue"), at_detect.get("run_queue"),
                at_start.get("nproc"),
                " OVERSUBSCRIBED" if at_start.get("over_cpus") else "",
                at_start.get("deadline"), hang.get("wedge")))
