# ---- [15] tests.d: one isolated task per group, coverage-pinned ----
#
# Why one sandbox per task: run-tests.sh points the `iprange` symlink in its
# own root at the binary it was handed (run-tests.sh:54) and derives its
# TEMP_DIR from that root, so two passes sharing one root would test whichever
# binary linked last.  Every (engine, group) pair therefore owns a directory,
# exactly as the single unsharded pass did -- splitting adds concurrency, not
# sharing.
#
# Why a group and not a shard is the unit of work: the execution policy caps
# an identifiable test at 15 s and forbids a grouping that hides a slow test.
# A shard of fifteen groups reports one duration for fifteen tests, so a
# 30 s group inside it is invisible in the duration table.  A per-group task
# names the group in its own TASKWALL/SLOWUNIT line, which is what makes the
# 15 s limit measurable here instead of merely asserted.
#
# Why splitting cannot lose a group: testsd_submit() enumerates the
# repository's own group list once per engine and records every group it
# handed to the pool.  testsd_coverage_gate() re-reads that list and requires
# each group to appear exactly once, so a split that dropped or doubled a
# group fails the battery instead of merely looking fast.
TESTSD_SUBMITTED_DIR="$R/testsd-plan"

testsd_groups() { find "$REPO/tests.d" -mindepth 1 -maxdepth 1 -type d -printf '%f\n' | LC_ALL=C sort; }

# testsd_run ENGINE BIN GROUP -- one isolated pass over one group.  The
# sandbox holds only what run-tests.sh reads: its own copy of the script and
# the one group directory.
testsd_run() {
  local eng=$1 bin=$2 group=$3
  local root="$R/W-testsd-$eng-$group"
  clean "$root"
  mkdir -p "$root/tests.d"
  cp "$REPO/run-tests.sh" "$root/"
  cp -r "$REPO/tests.d/$group" "$root/tests.d/"
  (cd "$root" && IPRANGE_BIN="$bin" nice bash run-tests.sh) > "$R/reports/log-testsd-$eng-$group.txt" 2>&1
}

# track_testsd_group ENGINE BIN GROUP -- the pool unit: run one group and
# record its verdict under a label that names the group.
track_testsd_group() {
  local eng=$1 bin=$2 group=$3
  testsd_run "$eng" "$bin" "$group"
  record "[15] tests.d $eng group $group" $? zero
}

# testsd_submit ENGINE BIN -- hand one pool task per group to the queue and
# record the hand-out for the coverage gate.
testsd_submit() {
  local eng=$1 bin=$2 g n=0 skipped=0 total=0
  mkdir -p "$TESTSD_SUBMITTED_DIR"
  : > "$TESTSD_SUBMITTED_DIR/$eng"
  while read -r g; do
    [ -n "$g" ] || continue
    total=$((total+1))
    # The one selection mechanism is run.py --filter, and it matches by
    # substring (run.py:3131).  The same flag therefore narrows the tests.d
    # group list the same way, so a targeted run costs a handful of seconds
    # instead of the whole suite.  A filtered pass measures; it does not
    # claim corpus coverage (see testsd_coverage_gate).
    if [ -n "$CASE_FILTER" ] && [[ "$g" != *"$CASE_FILTER"* ]]; then
      skipped=$((skipped+1)); continue
    fi
    printf '%s\n' "$g" >> "$TESTSD_SUBMITTED_DIR/$eng"
    SUBMIT_ORDER=$((SUBMIT_ORDER+1))
    submit "$SUBMIT_ORDER" "testsd-$eng-$g" track_testsd_group "$eng" "$bin" "$g"
    n=$((n+1))
  done < <(testsd_groups)
  TESTSD_SUBMITTED_COUNT=$n
  if [ -n "$CASE_FILTER" ]; then
    echo "testsd $eng: $n of $total group task(s) selected by --filter '$CASE_FILTER' ($skipped not selected; this pass does not claim whole-corpus coverage)"
  else
    echo "testsd $eng: $n group task(s), one isolated sandbox each"
  fi
}

# testsd_coverage_gate ENG -- called after the pool drains: the hand-out
# list, not a task's exit status, is what proves nothing was dropped to gain
# concurrency.
testsd_coverage_gate() {
  local eng=$1 bad=0 want have dup
  if [ -n "$CASE_FILTER" ]; then
    # A targeted pass selected a subset on purpose.  The whole-corpus claim
    # is still checked, but as an explicit statement of what was selected;
    # only a duplicate submission is a defect here.
    local sel dup
    sel=$(LC_ALL=C sort -u "$TESTSD_SUBMITTED_DIR/$eng" 2>/dev/null)
    dup=$(sort "$TESTSD_SUBMITTED_DIR/$eng" 2>/dev/null | uniq -d)
    printf 'TARGETED tests.d %s: --filter %s selected %d group(s) of %d\n' \
      "$eng" "$CASE_FILTER" "$(printf '%s\n' "$sel" | grep -c .)" \
      "$(testsd_groups | grep -c .)"
    if [ -n "$dup" ]; then
      echo "TESTSD SUBMISSION DOUBLES GROUPS for $eng: $dup"
      record "[15] tests.d $eng targeted selection" 1 zero; return
    fi
    record "[15] tests.d $eng targeted selection (filter active, not a whole-corpus pass)" 0 zero
    return
  fi
  want=$(testsd_groups)
  have=$(LC_ALL=C sort "$TESTSD_SUBMITTED_DIR/$eng" 2>/dev/null)
  if [ "$want" != "$have" ]; then
    echo "TESTSD SUBMISSION LOST GROUPS for $eng:"
    diff <(printf '%s\n' "$want") <(printf '%s\n' "$have") | sed 's/^/  /'
    bad=1
  fi
  dup=$(sort "$TESTSD_SUBMITTED_DIR/$eng" 2>/dev/null | uniq -d)
  if [ -n "$dup" ]; then
    echo "TESTSD SUBMISSION DOUBLES GROUPS for $eng: $dup"
    bad=1
  fi
  record "[15] tests.d $eng submission covers every group exactly once" "$bad" zero
}

