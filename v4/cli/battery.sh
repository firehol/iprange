track_matrix_rust() {
clean "$R/W-rust"
echo "### [5] matrix rust"

# Nothing downstream may judge a report this run did not author: a
# selector that empties a direction makes run.py exit before it writes
# anything, and the previous pass's file would then read as this pass's
# result.  Truncating first turns that into an explicit, checked state.
: > "$R/reports/matrix-rust.json"
nice python3 "$CLI/run.py" --go "$GOB" --rust "$RUB" --fixture-tool "$FIX" \
    --matrix "rust" --work-dir "$R/W-rust" --allow-skips \
    "${FILTER_ARGS[@]+"${FILTER_ARGS[@]}"}" \
    --json-report "$R/reports/matrix-rust.json" > "$R/reports/log-matrix-rust.txt" 2>&1
rc=$?
if [ -n "${CASE_FILTER:-}" ]; then
  # With --filter the runner exits nonzero for a direction the
  # selector legitimately emptied; the MATRIXCHECK step above is
  # what judges the run, so the raw status is reported, not judged.
  echo "TARGETED rc=$rc for matrix rust (judged by MATRIXCHECK)"
  record "[5] matrix rust" "$rc" any
else
  record "[5] matrix rust" "$rc" zero
fi
grep -E "passed|failed" "$R/reports/log-matrix-rust.txt" | tail -1
# run.py exits nonzero when any case failed, so a green rc is also the
# statement that the direction had no dead engine and recorded no
# matrix-level verdict; the two fields are checked independently because a
# run whose rows were rewritten must not be able to look clean.
python3 - "$R/reports/matrix-rust.json" "rust" "${CASE_FILTER:-}" >> "$R/reports/log-matrix-rust.txt" 2>&1 <<'MPY'
import json, sys
path, label, case_filter = sys.argv[1], sys.argv[2], (sys.argv[3] if len(sys.argv) > 3 else "")
try:
    with open(path) as _fh:
        d = json.load(_fh)
except (OSError, ValueError):
    # The track truncated this path before the runner started, so an empty
    # or missing file means the run authored no report.  With a selector that
    # is the selector's own outcome (run.py exits 'no cases selected');
    # without one it is a failed step, never a silent pass.
    if case_filter:
        print("MATRIXCHECK %s: run.py selected no case for this direction "
              "and authored no report (accepted as the selector's outcome)"
              % label)
        sys.exit(0)
    print("MATRIXCHECK %s: no report from this run" % label)
    sys.exit(1)
if case_filter:
    # A report that survives is only this run's if its own command line says
    # so; anything else is an artifact of an earlier pass.
    _cmd = d.get("command") or d.get("argv") or []
    if "--filter" not in _cmd or case_filter not in _cmd:
        print("MATRIXCHECK %s: %s was not authored by this --filter run "
              "(its command line ends %r); refusing to judge a stale artifact"
              % (label, path, list(_cmd)[-4:]))
        sys.exit(1)
deaths = d.get("engine_deaths") or []
verdicts = d.get("matrix_verdicts") or []
print("MATRIXCHECK %s: passed=%d failed=%d skipped=%d engine_deaths=%d matrix_verdicts=%d"
    % (label, d["passed"], d["failed"], d["skipped"], len(deaths), len(verdicts)))
for x in deaths:
  print("   DEAD %s phase=%s exit=%s case=%s" % (x.get("implementation"), x.get("phase"),
                                                 x.get("exit_status"), x.get("case")))
for v in verdicts:
  print("   VERDICT %s kind=%s: %s" % (v.get("matrix"), v.get("kind"), v.get("error")))
# A --filter run selects cases by name; a direction whose selected cases
# are all single-actor legitimately reports no-cases-executed.  That is the
# selector's outcome, not a defect, so it is accepted here and named.  A
# real engine death, a foreign verdict kind, or a failed case still fails.
bad_verdicts = [v for v in verdicts if v.get("kind") != "no-cases-executed"] if case_filter else verdicts
if case_filter and len(verdicts) == len(bad_verdicts) == 0 and not deaths and not d["failed"]:
    print("MATRIXCHECK %s: targeted (--filter %s) selected no case this "
          "direction can execute; accepted as the selector's outcome"
          % (label, case_filter))
if d["failed"]:
    print("MATRIXCHECK %s: %d failed case(s)" % (label, d["failed"]))
sys.exit(0 if (not deaths and not bad_verdicts and not d["failed"]) else 1)
MPY
record "[5] matrix rust has no dead engine or verdict" $? zero
}

