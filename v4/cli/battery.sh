    record "$label" "$rc" zero
  fi
}

# A provenance note is only useful if it is true for this run: it names the
# wave, the staging root, and the binary ledger the artifacts are bound to.
# It must never carry a workstation path.  Every gate that accepts
# --provenance-note hands the string to the shared committed-report writer, and
# that writer refuses the whole report when any string names the operator's
# profile -- which, on this workstation, the checkout sits inside.  A note
# spelled with the absolute checkout path therefore failed the [9b] parity gate
# and the [14] race battery after both sweeps had already passed: the prose
# was the defect, not the measurement.  The note is composed from the
# sanitizer's own checkout-relative rendering and re-checked here with the very
# scanner the writer applies, so the class fails once at [0p] instead of
# silently at every gate that takes the flag.
render_provenance_note() {
  nice python3 - "$CLI" "$R/bin" "$BIN/SHASUMS.txt" "$SHASUMS" <<'PNY'
import os
import re
import sys
sys.path.insert(0, sys.argv[1])
import command_sanitize as cs

_, cli_dir, staging_bin, ledger_bin, ledger_copy = sys.argv
note = ("wave-19.25 Linux battery; engines staged under the wave staging root"
        " labelled %s and bound by the staged-binary ledger %s (entries are"
        " staging-relative digests); no requirement waiver"
        % (os.path.basename(os.path.dirname(staging_bin.rstrip("/"))),
           cs.sanitized_path_value(ledger_bin)))
problems = []
hit = cs.personal_path_in_report({"provenance_note": note})
if hit is not None:
    problems.append("the note carries a personal path: %r" % hit)
root = cs.checkout_root()
if root and root in note:
    problems.append("the note repeats the checkout root verbatim")
for absolute in re.findall(r"(?<![\w.])/(?:[\w.\-]+/?)+|[A-Za-z]:[\\/]", note):
    problems.append("the note carries an absolute path: %r" % absolute)
if not note.startswith("wave-19.25 "):
    problems.append("the note no longer names the wave")
if "no requirement waiver" not in note:
    problems.append("the note dropped the no-requirement-waiver clause")
for problem in problems:
    print("PROVENANCE-NOTE PROBLEM %s" % problem)
if problems:
    sys.exit(1)
sys.stdout.write(note + "\n")
PNY
}
