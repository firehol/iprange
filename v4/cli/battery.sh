# evidence.  Every engine and the fixture tool must be a staged binary whose
# SHA-256 the ledger carries under its staging-relative name, and the two ledger
# copies the provenance note names must still agree with each other.
def file_sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as stream:
        for block in iter(lambda: stream.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()

def ledger_table(path):
    table = {}
    with open(path, encoding="utf-8") as stream:
        for line in stream:
            fields = line.split()
            if len(fields) == 2:
                table[fields[1]] = fields[0]
    return table

