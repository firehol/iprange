# The battery waits on a per-attempt deadline, so a silent attempt is ambiguous
# unless the report says whether the host could run the engine at all.  Every
# record has to answer that, and no answer -- however overloaded the host was
# -- may talk a product-arm hang out of being a failure.
HOST_CONTEXT_KEYS = ("source", "nproc", "deadline", "samples", "run_queue",
                     "loadavg_1m", "over_cpus_samples", "oversubscribed")
HOST_SAMPLE_KEYS = ("source", "nproc", "deadline", "loadavg_1m", "run_queue",
                    "over_cpus")


def sample_problem(sample, where):
    if not isinstance(sample, dict):
        return "%s: host sample is %s, not a mapping" % (where, type(sample).__name__)
    absent = [key for key in HOST_SAMPLE_KEYS if key not in sample]
    if absent:
        return "%s: missing %s" % (where, sorted(absent))
    cpus, queue = sample["nproc"], sample["run_queue"]
    if not isinstance(cpus, int) or cpus < 1:
        return "%s: nproc is %r" % (where, cpus)
    if not isinstance(sample["deadline"], (int, float)) or sample["deadline"] <= 0:
        return "%s: deadline is %r" % (where, sample["deadline"])
    if sample["loadavg_1m"] is None and queue is None:
        return "%s: neither loadavg_1m nor run_queue was obtainable" % where
    if queue is not None and sample["over_cpus"] != (queue > cpus):
        return ("%s: over_cpus says %r but run_queue %s against nproc %s says %s"
                % (where, sample["over_cpus"], queue, cpus, queue > cpus))
    return None


def context_problem(record):
    context = record.get("host_context")
    if not isinstance(context, dict):
        return ("carries no host_context: a battery that waits on a deadline "
                "has to say what the host was doing while it waited")
    absent = [key for key in HOST_CONTEXT_KEYS if key not in context]
    if absent:
        return "host_context is missing %s" % sorted(absent)
    if not isinstance(context["samples"], int) or context["samples"] < 1:
        return "host_context sampled %r attempts" % (context["samples"],)
    if context["run_queue"] is None and context["loadavg_1m"] is None:
        return "host_context recorded neither a run queue nor a load average"
    spread = context["run_queue"] or {}
    median = spread.get("median") if isinstance(spread, dict) else None
    if median is not None and context["oversubscribed"] != (median > context["nproc"]):
        return ("host_context oversubscribed says %r but the sampled run queue "
                "median %s against nproc %s says %s"
                % (context["oversubscribed"], median, context["nproc"],
                   median > context["nproc"]))
    return None


def hang_observations(record):
    """The silent attempts a record claims, one observation each."""
    hangs = record.get("hangs")
    if isinstance(hangs, list):
        return hangs
    if isinstance(hangs, int):
        return record.get("hang_observations") or [
            None for _ in range(hangs)]
    return []


for record in entries:
    where = record.get("subject") or record.get("subject_label") or "record"
    problem = context_problem(record)
    if problem is not None:
        problems.append("%s %s" % (where, problem))
    observations = hang_observations(record)
    claimed = record.get("hangs")
