    if not real.startswith(root):
        problems.append("%s (%s) is not under the staging root" % (name, path))
        continue
    relative = os.path.relpath(real, os.path.realpath(staging_bin))
    if ledger.get(relative) != digest:
        problems.append("%s digest %s is not the ledger's %s for %s"
                        % (name, str(digest)[:12],
                           str(ledger.get(relative))[:12], relative))

for e in arms:
    w = e.get("timing_window") or {}
    a = e.get("replacement_activity") or {}
    print("   %s/%s to_fifo=%s toggles=%s in_flight_to_fifo=%s exercised=%s" % (
        e.get("engine"), e.get("arm"), a.get("to_fifo"), a.get("toggles"),
        w.get("in_flight_to_fifo"), w.get("exercised")))
for f in d.get("failures", [])[:8]:
    print("   FAILURE %s[%s]: %s" % (f.get("class"), f.get("subject"),
                                     str(f.get("detail"))[:160]))
for problem in problems:
    print("   RACECHECK PROBLEM %s" % problem)
sys.exit(1 if problems else 0)
RPY
  record "[14] race artifact present" $? zero
else
  echo "RACECHECK: no race-battery.json was written; the battery produced no verdict"
  record "[14] race artifact present" 1 zero
fi
