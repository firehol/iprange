# record LABEL RC EXPECT(zero|nonzero|any)
record() {
  local label="$1" rc="$2" want="$3" ok=OK
  if [ "$want" = zero ] && [ "$rc" -ne 0 ]; then ok=MISMATCH
  elif [ "$want" = nonzero ] && [ "$rc" -eq 0 ]; then ok=MISMATCH; fi
  # A pooled task records into its own outcome file and the battery
  # replays those lines in submission order; a serial step prints them
  # directly.  Both paths count the same way, so parallelism cannot
  # change what "steps checked" means.
  if [ -n "${TRACK_OUTCOME:-}" ]; then
    printf '%s\t%s\t%s\t%s\n' "$label" "$rc" "$want" "$ok" >> "$TRACK_OUTCOME"
    return 0
  fi
  STEPS=$((STEPS+1))
  [ "$ok" = OK ] || STEPFAIL=$((STEPFAIL+1))
  echo "STEPRESULT $label rc=$rc expect=$want $ok"
}

# record_deferred LABEL REASON [GATE_RC]
# A step whose obligation belongs to another leg of the wave is neither OK nor
# MISMATCH: it is DEFERRED, counted separately, and always listed in the
# summary.  Recording it OK would let a Linux battery look green on an artifact
# it never produced; recording it MISMATCH would bury a real defect under the
# known ones.  Only the leg that owns the artifact can clear it.
#
# GATE_RC is the exit status the step really produced and is printed verbatim.
# Printing 0 for a gate that exited nonzero would read as a clean pass to
# anyone who greps "rc=0" without reading the status word, which is the
# greenwash this label exists to avoid.
record_deferred() {
  local label="$1" reason="$2" gate_rc="${3:-0}"
  case "$gate_rc" in ""|*[!0-9]*) gate_rc=0;; esac
  # A pooled task defers into its own outcome file and the battery replays
  # the line, exactly as record() does; a deferral that only reached the
  # task's stdout would leave the outcome file empty and the replay would
  # report the task as having checked nothing.
  if [ -n "${TRACK_OUTCOME:-}" ]; then
    printf '%s\t%s\t%s\t%s\n' "$label" "$gate_rc" zero "DEFERRED ($reason)" >> "$TRACK_OUTCOME"
    return 0
  fi
  STEPS=$((STEPS+1)); DEFERRED=$((DEFERRED+1))
  echo "STEPRESULT $label rc=$gate_rc expect=zero DEFERRED ($reason)"
}

# record_audit LABEL RC LOGFILE
# A committed-evidence audit is red for two different reasons and only one of
# them belongs to this host.  The windows-* reports are authored on the
# authorized Windows validation host, so a Linux leg can never clear their
# provenance or privacy complaints.  An audit whose every problem is one of
# those is named as outstanding and recorded DEFERRED; any other problem is
# this battery's own defect and keeps its real exit status.  The step can
# therefore never go quietly green on a report the audit refuses for a reason
# that belongs to another leg of the wave, and a deferred step is never
# mistaken for a passing one.
record_audit() {
  local label="$1" rc="$2" log="$3" foreign here
  if [ "$rc" -eq 0 ]; then record "$label" 0 zero; return; fi
  # The two audit entry points name artifacts differently: the committed-report
  # path says "evidence/windows-guard.json" and the writer-registry path says
  # "windows-guard.json".  Both spellings must be recognised here, or a
  # Windows-only remainder is miscounted as this battery's own defect and the
  # step mismatches on every Linux run.
  foreign=$(grep -cE '^PROBLEM (evidence/)?windows-' "$log" 2>/dev/null)
  case "$foreign" in ""|*[!0-9]*) foreign=0;; esac
  here=$(grep -c '^PROBLEM ' "$log" 2>/dev/null)
  case "$here" in ""|*[!0-9]*) here=1;; esac
  if [ "$here" -gt 0 ] && [ "$here" -eq "$foreign" ]; then
    echo "$label: every outstanding problem is a Windows-leg artifact;"
    echo "  these are refreshed by the Windows leg of the wave, never here:"
    grep '^PROBLEM ' "$log" | sed 's/^/  /'
    record_deferred "$label" "native Windows leg owns these artifacts" "$rc"
  else
    echo "$label: $((here - foreign)) problem(s) are this battery's own:"
    grep '^PROBLEM ' "$log" | grep -vE '^PROBLEM (evidence/)?windows-' | sed 's/^/  /'
    record "$label" "$rc" zero
  fi
}

# windows_hold LOGFILE CONSUMED... -- exit 0 when every complaint in LOGFILE is
# attributable to the two Windows-leg artifacts this Linux leg does not author.
#
# Attribution is per complaint and all-or-nothing: one line that names any
# artifact other than a windows-* report keeps the step red, so a deferral can
# never shelter a defect of this run.  A revision-disagreement complaint is
# judged from the consumed files themselves rather than from its prose: the
# reports that do not name the revision under test must all be Windows-leg
# artifacts.  The classification is printed either way, so a reader can check a
# deferral without rerunning the gate.
windows_hold() {
  local log="$1"; shift
  nice python3 - "$log" "$REPO" "$@" <<'WHY'
import ast
import json
import os
import re
import subprocess
import sys

log_path, repo = sys.argv[1], sys.argv[2]
consumed = sys.argv[3:]
try:
    head = subprocess.run(["git", "-C", repo, "rev-parse", "HEAD"],
                          capture_output=True, text=True).stdout.strip()
except OSError:
    head = ""
head12 = head[:12]

GATE_ASSERTION = re.compile(r"genuine evidence failed the(?: consumed-class"
                            r" configuration|) gate:\s*(\[.*\])")
PREFIXES = ("FAIL: ", "baseline: ", "VERIFY ", "PROBLEM ")


def base_names(text):
    return [os.path.basename(match) for match in
            re.findall(r"([^\s,;()\[\]{}'\"]+\.json)", text)]


def revision_complaint_is_windows_only():
    """Judge a revision-disagreement from the files, not from the prose.

    Every consumed report that does not name the revision under test has to be
    a Windows-leg artifact; one stale matrix, crash, or coverage report is this
    leg's own defect and makes the answer no.
    """
    stale = []
    for path in consumed:
        try:
            with open(path, encoding="utf-8") as stream:
                document = json.load(stream)
        except (OSError, ValueError):
            return False                  # unreadable: nothing to defer
        if not isinstance(document, dict):
            return False
        recorded = document.get("git_head")
        if recorded is None:
            continue
        if str(recorded)[:12] != head12:
            stale.append(os.path.basename(path))
    return bool(stale) and all(name.startswith("windows-") for name in stale)


# The gate prefixes each problem with the report class it came from, so a
# complaint about the Windows housekeeping artifact reads "windows <path>: ..."
# whatever the file is called.  Name matching alone is not enough: the forgery
# battery hands the gate its own sandbox copies, which it names after the
# mutation class under test ("<tag>-baseline-windows.json"), and a rule that
# only recognised "windows-*" would report those as this leg's own defect.
# The prefix is the gate's own statement of class, and it is checked in
# addition to -- never instead of -- the file names, so a complaint that also
# names a Linux-produced report stays this leg's.
WINDOWS_CLASSES = ("windows ", "windows-housekeeping ", "windows-guard ")


def attributable(text):
    if "disagree about the source revision" in text or \
            "no single revision covers the battery" in text:
        return revision_complaint_is_windows_only()
    names = base_names(text)
    if names and not all(name.startswith("windows-") for name in names):
        # A sandbox copy is named for the class under test, not for the report
        # it holds; only the gate's own class prefix can claim it, and only
        # when the complaint names no artifact this leg is responsible for.
        if not text.startswith(WINDOWS_CLASSES):
            return False
        names = [name for name in names if not name.endswith("-windows.json")]
        if not names:
            return True
        return all(name.startswith("windows-") for name in names)
    return bool(names)


complaints = 0
local = []
for line in open(log_path, encoding="utf-8", errors="replace"):
    stripped = line.strip()
    match = GATE_ASSERTION.search(stripped)
    if match:
        # The gate's own --self-test reports the blocking problems as a Python
        # list inside an AssertionError, not as prefixed lines.
        try:
            problems = ast.literal_eval(match.group(1))
        except (SyntaxError, ValueError):
            problems = [stripped]
        if not isinstance(problems, list):
            problems = [problems]
        for text in problems:
            complaints += 1
            if not attributable(str(text)):
                local.append(str(text))
        continue
    for prefix in PREFIXES:
        if not stripped.startswith(prefix):
            continue
        complaints += 1
        if not attributable(stripped[len(prefix):]):
            local.append(stripped)
        break

print("WINDOWS-HOLD: %d complaint(s), %d local to this leg"
      % (complaints, len(local)))
for text in local[:12]:
    print("  LOCAL %s" % text[:300])
if len(local) > 12:
    print("  ... and %d more local complaint(s)" % (len(local) - 12))
sys.exit(0 if complaints and not local else 1)
WHY
}

# record_gate LABEL RC LOGFILE CONSUMED... -- a gate whose only outstanding
# complaints are the held-out Windows artifacts is DEFERRED under its own label
# and counted separately; anything else keeps the gate's real exit status.
record_gate() {
  local label="$1" rc="$2" log="$3"; shift 3
  if [ "$rc" -eq 0 ]; then record "$label" 0 zero; return; fi
  if windows_hold "$log" "$@"; then
    echo "$label: the gate refused only the Windows-leg artifacts this leg does"
