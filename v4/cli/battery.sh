# ---------------------------------------------------------------------
# One bounded worker pool for the standard suite.
#
# Every standard unit (a Rust test binary, a tests.d shard, one CLI
# matrix, one gate, one harness self-test) is submitted as a task and
# admitted through the same POOL_JOBS-wide pool.  That is what makes
# "one overall concurrency budget" true instead of aspirational: the
# cap is on concurrent leaf processes for the whole suite, not per
# harness, so twenty harnesses that each default to "use every core"
# cannot turn a 60 s suite into a 20-way over-subscribed 600 s one.
#
# Isolation is part of the contract, not an afterthought:
#   * each task owns $R/tasks/NNN-name/ and writes only there;
#   * each tests.d pass owns its own sandbox root, because run-tests.sh
#     points the repo-root `iprange` symlink at the binary it was handed
#     (run-tests.sh:54 in the sandbox copy), so two concurrent passes
#     against one root would test whichever binary linked last;
#   * a task never writes a committed path.
#
# Assertions are not weakened by the parallelism: a task records through
# the same record/record_gate/record_audit helpers the serial steps use,
# into its own outcome file, and the battery replays those outcomes in
# submission order, so `steps checked / mismatches / deferred` counts
# exactly what it counted before and in the same order.
# ---------------------------------------------------------------------
TASKS="$R/tasks"
mkdir -p "$TASKS"

# submit ORDER NAME FUNCTION [ARG ...]
# ORDER is a replay hint; the long-pole tracks are submitted first so the
# pool starts them first.  FUNCTION is a battery function that runs one
# identifiable unit and records through record/record_gate.  Extra
# arguments are passed verbatim to FUNCTION, so one parameterised function
# can own many units (one tests.d group each) without a generated wrapper
# per unit.
SUBMITTED=()
submit() {
  local order=$1 name=$2 func=$3
  shift 3
  local dir="$TASKS/$(printf '%03d-%s' "$order" "$name")"
  local argv="" a
  for a in "$@"; do argv="${argv} $(printf '%q' "$a")"; done
  mkdir -p "$dir"
  cat > "$dir/task.sh" <<TEOF
#!/usr/bin/env bash
set -u
export TRACK_OUTCOME="$dir/outcomes"
. "$TASKS/common.sh"
$func${argv}
TEOF
  chmod +x "$dir/task.sh"
  : > "$dir/outcomes"
  SUBMITTED+=("$(printf '%03d-%s' "$order" "$name")|$func|$argv")
}

# Shared preamble every task sources: the scalars, the recorders and the
# track function itself, so a task's assertions go through the same code
# path as a serial step's.
emit_common() {
  {
    printf 'REPO=%q\nR=%q\nBIN=%q\nCLI=%q\n' "$REPO" "$R" "$BIN" "$CLI"
    printf 'STEPS=%q\nSTEPFAIL=%q\nDEFERRED=%q\n' 0 0 0
    printf 'GOB=%q\nGOW=%q\nRUB=%q\nRUW=%q\nFIX=%q\n' "$GOB" "$GOW" "$RUB" "$RUW" "$FIX"
    printf 'SHASUMS=%q\nCASE_FILTER=%q\nPN=%q\n' "$SHASUMS" "$CASE_FILTER" "${PN:-}"
    printf 'IPRANGE_JOBS=%q\nRECORDINGS=%q\n' "$POOL_JOBS" "$R/reports"
    printf 'NEED_PRESSURE_FULL=%q\n' "$NEED_PRESSURE_FULL"
    declare -f clean record record_deferred record_gate record_audit prov_array
    declare -f windows_hold
    declare -f testsd_run testsd_groups
    printf 'NEED_TESTSD_C=%q\nCCB=%q\n' "$NEED_TESTSD_C" "${CCB:-}"
    printf 'TIER=%q\nIPRANGE_RUST_FRESH_EVERY_RUN=%q\nR_RUSTFRESH=%q\n' "$TIER" "${IPRANGE_RUST_FRESH_EVERY_RUN:-0}" "$R_RUSTFRESH"
    # The same parameterised function backs many tasks (one per tests.d
    # group), so each function is emitted once, not once per task.
    local entry func seen
    declare -A EMITTED_FUNC=()
    for entry in "${SUBMITTED[@]}"; do
      func=${entry#*|}; func=${func%%|*}
      [ -n "${EMITTED_FUNC[$func]:-}" ] && continue
      declare -f "$func" >/dev/null || { echo "POOL: unknown track function $func" >&2; return 1; }
      EMITTED_FUNC[$func]=1
      declare -f "$func"
    done
    # The targeted-run selector is the runner's own; a task must see it.
    printf 'FILTER_ARGS=('
    for seen in "${FILTER_ARGS[@]+"${FILTER_ARGS[@]}"}"; do printf ' %q' "$seen"; done
    printf ')\n'

    # A pooled gate self-test is judged against the committed report set, so
    # it needs the same artifact paths the serial gate passes read.
    printf 'COMMITTED_CONSUMED_PATHS=('
    for seen in "${COMMITTED_CONSUMED_PATHS[@]+"${COMMITTED_CONSUMED_PATHS[@]}"}"; do printf ' %q' "$seen"; done
    printf ')\n'

  } > "$TASKS/common.sh"
}

# pool_drain -- run every submitted task under the one budget.
pool_drain() {
  emit_common || return 1
  local list="$TASKS/list"
  : > "$list"
  local entry
  for entry in "${SUBMITTED[@]}"; do printf '%s\n' "${entry%%|*}" >> "$list"; done
  local fail=0
  # xargs -P is the one queue: nothing else admits a standard task, so
  # POOL_JOBS is the suite-wide cap rather than one cap per track.
  nice xargs -P "$POOL_JOBS" -I '{}' -a "$list" \
    bash -c 'd="'"$TASKS"'/$1"; s=$(date +%s.%N); nice bash "$d/task.sh" > "$d/log" 2>&1; rc=$?; e=$(date +%s.%N); echo "$rc" > "$d/rc"; echo "$s" > "$d/t0"; echo "$e" > "$d/t1"; awk -v s="$s" -v e="$e" "BEGIN{printf \"%.2f\", e-s}" > "$d/wall"' _ {} || fail=$?
  [ "$fail" -eq 0 ] || echo "POOL: xargs reported a task failure (rc=$fail)"
}

# replay -- print every task's outcome lines in submission order and
# fold them into the battery counters, exactly as a serial step would.
replay() {
  local entry t dir n=0 bad=0
  for entry in "${SUBMITTED[@]}"; do
    t=${entry%%|*}
    dir="$TASKS/$t"
    [ -d "$dir" ] || continue
    n=$((n+1))
    local wall; wall=$(cat "$dir/wall" 2>/dev/null || echo NA)
    # TASKWALL is the machine-readable duration table the SOW's measured
    # evidence requires: one line per unit, its exit status, and the wall
    # time it cost inside the pool.  A suite that cannot name its own
    # durations cannot claim a budget.
    echo "TASKWALL $t rc=$(cat "$dir/rc" 2>/dev/null || echo NA) wall=${wall}s"
    echo "### [task $t] rc=$(cat "$dir/rc" 2>/dev/null || echo NA) log=$dir/log"
    local line label rc want ok
    while IFS=$'\t' read -r label rc want ok; do
      [ -n "$label" ] || continue
      STEPS=$((STEPS+1))
      if [ "$ok" = OK ]; then :
      elif [ "${ok#DEFERRED}" != "$ok" ]; then
        # Deferred work is neither a pass nor a mismatch: it is an
        # obligation this leg cannot discharge, counted and listed.
        DEFERRED=$((DEFERRED+1))
      else
        STEPFAIL=$((STEPFAIL+1)); bad=$((bad+1))
      fi
      echo "STEPRESULT $label rc=$rc expect=$want $ok"
    done < "$dir/outcomes"
    if [ ! -s "$dir/outcomes" ]; then
      # A task that recorded nothing checked nothing: say so loudly
      # rather than letting an empty outcome file read as a clean pass.
      echo "STEPRESULT [task $t] rc=$(cat "$dir/rc" 2>/dev/null || echo NA) expect=zero MISMATCH"
      STEPS=$((STEPS+1)); STEPFAIL=$((STEPFAIL+1)); bad=$((bad+1))
    fi
    tail -n "${TASK_LOG_TAIL:-6}" "$dir/log" 2>/dev/null | sed 's/^/    /'
  done
  # The 15 s limit in the test suite execution policy applies to an
  # identifiable test, setup and cleanup included.  A pooled unit IS an
  # identifiable test, so the suite names any unit over the limit instead
  # of leaving the reader to discover it in a log after the fact.  This is
  # a report, not a verdict: a unit over the limit is a decision for the
  # lead (fix its serialization or demote it explicitly), and failing the
  # battery here would hide a real product defect behind a policy line.
  local over=0
  for entry in "${SUBMITTED[@]}"; do
    t=${entry%%|*}; dir="$TASKS/$t"
    local w; w=$(cat "$dir/wall" 2>/dev/null || echo 0)
    if awk -v w="$w" 'BEGIN{exit !(w>15)}'; then
      echo "SLOWUNIT $t wall=${w}s (policy: an identifiable test must stay at or under 15s)"
      over=$((over+1))
    fi
  done
  echo "pool: $n task(s) drained at $POOL_JOBS-wide concurrency, $bad mismatching outcome(s), $over unit(s) over the 15 s policy"
}

