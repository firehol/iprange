# The Rust workspace is one pool task.
#
# It was split into one task per package on the theory that three packages
# could share the pool; measured, that is false.  Concurrent `cargo test`
# invocations over one CARGO_TARGET_DIR block on the build-directory lock
# (4-5 "Blocking waiting for file lock" lines per invocation when three run
# together), so the split serialises anyway and adds lock-wait noise.  The
# workspace therefore stays one unit: `cargo test --workspace` under nice, all
# packages, unit + integration + doc tests, exit status recorded.
#
# Measured cost of this unit on this host (24 cores, warm target dir): the
# 59 test binaries account for 66.3 s of wall time and the three package
# invocations for 86.6 s (41.1 iprange-livedb, 38.9 iprange-cli, 6.7
# iprange-capi); the difference is doc-test compilation.  A pre-built
# `cargo test --workspace --no-run` plus direct execution of the compiled
# test binaries would put the unit at its 10.1 s slowest binary, but it
# silently drops the doc tests, so it is a coverage decision and not an
# optimisation this file may make on its own.
track_rust_unit() {
echo "### [3] full Rust workspace tests"
# Fresh means fresh, when this run paid for a build: the tree the tests build
# into is emptied first, so the recorded "cargo test" wall time cannot be a
# warm-reuse number wearing a fresh build's label.  --tier standard does not
# build (see --build), so it reuses the directory instead of emptying a tree
# the suite would then have to rebuild inside a 60 s budget.
if [ "$TIER" = full ] || [ "${IPRANGE_RUST_FRESH_EVERY_RUN:-0}" = 1 ]; then
  clean "$R_RUSTFRESH"
else
  mkdir -p "$R_RUSTFRESH"
fi
# The legacy pins' UNSCORED contract (io::caller_open record_unsupported
# and legacy::tests record_unscored_pin): a fixture a host cannot build
# is only survivable when it is RECORDED in the tally; with no tally
# configured the pin fails rather than passing unverified. Exporting the
# variable here means a root battery run (or any host missing a fixture)
# lands its reasons in a checked artifact instead of a silent pass;
# unprivileged runs keep the file empty.
(cd "$REPO" && export CARGO_TARGET_DIR="$R_RUSTFRESH" CARGO_HOME="$REPO/.local/int-prep/cargo-home" IPRANGE_V4_WIN_PIN_TALLY="$R/reports/linux-pin-tally.txt" && \
  nice cargo build --manifest-path v4/rust/Cargo.toml -p iprange-livedb --bins >> "$R/reports/rust-test.log" 2>&1 && \
  nice cargo test --manifest-path v4/rust/Cargo.toml >> "$R/reports/rust-test.log" 2>&1)
record "[3] cargo test" $? zero
tail -3 "$R/reports/rust-test.log"
# The tally is judged, not just collected: every UNSCORED line names a
# pin that ran unverified, and the run must say so loudly. 0 is the
# expected value for an unprivileged Linux host.
touch "$R/reports/linux-pin-tally.txt"
_linux_unscored=$(grep -c '^UNSCORED' "$R/reports/linux-pin-tally.txt" 2>/dev/null || true)
echo "LINUX_PIN_TALLY unscoped=${_linux_unscored:-0} file=reports/linux-pin-tally.txt" >> "$R/reports/rust-test.log"
# Warning CLASS gate: rustc exits 0 through a dead cfg value (rounds 2-3
# shipped target_os="darwin" exactly this way). The native legs pin
# warning-count 0; the battery pins the same rule here so no leg can
# attest a tree that warns.
if grep -q '^warning' "$R/reports/rust-test.log"; then
  echo "RUST_WARNING_GATE: rustc warnings present in rust-test.log (fail-closed)" >> "$R/reports/rust-test.log"
  record "[3b] rust warning gate" 1 zero
else
  record "[3b] rust warning gate" 0 zero
fi
}

