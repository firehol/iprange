wanted = {"%s/%s" % (engine, arm)
          for engine in d.get("binaries", {})
          for arm in d.get("options", {}).get("arms", [])}
raced = {"%s/%s" % (e.get("engine"), e.get("arm")) for e in arms}
if raced != wanted:
